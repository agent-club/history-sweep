export function linkCleanupText(language, key, values = {}) {
  const entry = copy[key];
  if (!entry) throw new Error(`Unknown link cleanup copy: ${key}`);
  return entry[language === 'zh-CN' ? 1 : 0].replace(/\{(\w+)\}/g, (_, name) => String(values[name]));
}
