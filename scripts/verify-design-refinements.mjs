const sampleContrast = (foreground, background, pseudo = '') => page.evaluate(({ foreground, background, pseudo }) => {
  const parse = value => {
    const parts = value.match(/[+-]?(?:\d*\.)?\d+/g)?.map(Number);
    return parts?.length >= 3 ? { r: parts[0], g: parts[1], b: parts[2], a: parts[3] ?? 1 } : null;
  };
  const composite = (top, base) => {
    const a = top.a + base.a * (1 - top.a);
    if (!a) return { r: 0, g: 0, b: 0, a: 0 };
    return { r: (top.r * top.a + base.r * base.a * (1 - top.a)) / a, g: (top.g * top.a + base.g * base.a * (1 - top.a)) / a, b: (top.b * top.a + base.b * base.a * (1 - top.a)) / a, a };
  };
  const backgroundColor = element => {
    const layers = [];
    for (let node = element; node; node = node.parentElement) {
      const color = parse(getComputedStyle(node).backgroundColor);
      if (color && color.a > 0) layers.push(color);
    }
    let color = { r: 255, g: 255, b: 255, a: 1 };
    for (const layer of layers.reverse()) color = composite(layer, color);
    return color;
  };
  const fg = document.querySelector(foreground), bg = document.querySelector(background);
  if (!fg || !bg) return { skipped: 'missing element' };
  if (fg.disabled) return { skipped: 'disabled control' };
  const style = pseudo ? getComputedStyle(fg, pseudo) : getComputedStyle(fg), content = pseudo ? fg.getAttribute('placeholder') || '' : fg.textContent.trim();
  if (!content) return { skipped: 'no meaningful text' };
  const color = parse(style.color), base = backgroundColor(bg);
  if (!color) return { skipped: 'unresolved computed color' };
  const effective = composite(color, base);
  const linear = channel => { const value = channel / 255; return value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4; };
  const luminance = value => 0.2126 * linear(value.r) + 0.7152 * linear(value.g) + 0.0722 * linear(value.b);
  const [lighter, darker] = [luminance(effective), luminance(base)].sort((a, b) => b - a);
  return { fontSize: style.fontSize, foreground: style.color, background: `rgb(${Math.round(base.r)}, ${Math.round(base.g)}, ${Math.round(base.b)})`, ratio: (lighter + 0.05) / (darker + 0.05), content };
}, { foreground, background, pseudo });
