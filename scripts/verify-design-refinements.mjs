const installStorageFailure = key => page.evaluate(key => {
  const area = chrome.storage.local;
  const own = Object.getOwnPropertyDescriptor(area, 'set');
  const original = area.set.bind(area);
  Object.defineProperty(area, 'set', { configurable: true, value: async items => {
    if (Object.prototype.hasOwnProperty.call(items, key)) throw new Error('synthetic storage failure');
    return original(items);
  } });
  window.__restoreSyntheticStorageSet = () => {
    if (own) Object.defineProperty(area, 'set', own);
    else delete area.set;
  };
}, key);
