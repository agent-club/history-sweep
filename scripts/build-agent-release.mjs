import { mkdir, readFile, writeFile, stat } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { VERSION, BUNDLE_FILES } from '../agent/metadata.mjs';
import { createInstallerDownload } from '../extension/agent-installers.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const outputIndex = process.argv.indexOf('--output');
if (outputIndex < 0 || !process.argv[outputIndex + 1]) throw new Error('Supply --output with a new staging directory');
const output = resolve(process.argv[outputIndex + 1]);
try { await stat(output); throw new Error('Output exists; choose a new staging directory to preserve its contents'); }
catch (error) { if (error.code !== 'ENOENT') throw error; }
const digest = bytes => createHash('sha256').update(bytes).digest('hex');
await mkdir(output, { recursive: true });
const files = [];
for (const path of BUNDLE_FILES) {
  const bytes = await readFile(join(root, 'agent', path));
  const destination = join(output, 'releases', VERSION, path);
  await mkdir(dirname(destination), { recursive: true });
  await writeFile(destination, bytes);
  files.push({ path, size: bytes.length, sha256: digest(bytes), url: `https://sweep.agentclub.dev/agent/releases/${VERSION}/${path}` });
}
const bootstrap = await readFile(join(root, 'agent', 'bootstrap.mjs'));
const bootstrapSha256 = digest(bootstrap);
await writeFile(join(output, 'bootstrap.mjs'), bootstrap);
await writeFile(join(output, 'latest.json'), JSON.stringify({ schemaVersion: 1, version: VERSION, files }, null, 2) + '\n');
const metadataPath = join(root, 'extension', 'agent-release.mjs');
const before = await readFile(metadataPath, 'utf8').catch(error => { if (error.code === 'ENOENT') return null; throw error; });
const header = '// Generated by scripts/build-agent-release.mjs; bootstrap checksum is pinned in the extension.\n';
if (before !== null && !before.startsWith(header)) throw new Error('Preserve the existing agent-release.mjs; it is not a managed generated file');
await writeFile(metadataPath, `${header}export const agentRelease = ${JSON.stringify({ version: VERSION, bootstrapSha256 }, null, 2)};\n`);
const idIndex = process.argv.indexOf('--extension-id');
if (idIndex >= 0) {
  for (const platform of ['windows', 'linux']) for (const client of ['codex', 'claude-code']) {
    const archive = createInstallerDownload({ platform, client, extensionId: process.argv[idIndex + 1], bootstrapSha256 });
    await writeFile(join(output, `${client}-${archive.filename}`), archive.bytes);
  }
}
console.log(JSON.stringify({ directory: output, version: VERSION, files: files.length, bootstrapSha256,
  publication: 'Prepared locally; upload this directory under /agent/ only after publication is authorized.' }, null, 2));
